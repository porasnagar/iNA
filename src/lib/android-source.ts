function languageOf(name: string): SourceLanguage {
  if (name.endsWith(".kt")) return "kotlin";
  if (name.endsWith(".kts")) return "gradle";
  if (name.endsWith(".xml")) return "xml";
  return "text";
}

export const SOURCE_FILES: SourceFile[] = Object.entries(RAW)
  .map(([fullPath, content]) => {
    const path = fullPath.replace(/^\/src\/android\//, "");
    const name = path.split("/").pop() ?? path;
    return {
      path,
      name,
      language: languageOf(name),
      content,
      primary: PRIMARY_ORDER.includes(name),
      description: DESCRIPTIONS[name] ?? (path.includes("/") ? path.slice(0, path.lastIndexOf("/")) : "Project root"),
    };
  })
  .sort((a, b) => {
    const ai = PRIMARY_ORDER.indexOf(a.name);
    const bi = PRIMARY_ORDER.indexOf(b.name);
    if (ai !== -1 || bi !== -1) return (ai === -1 ? 99 : ai) - (bi === -1 ? 99 : bi);
    return a.path.localeCompare(b.path);
  });

export const EMBEDDED_ART_FILE = "EmbeddedProductArt.kt";

async function loadImage(url: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = "anonymous";
    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error(`Could not load ${url}`));
    img.src = url;
  });
}

/** Downscales a render for embedding (keeps the Kotlin file a sane size). */
async function imageToBase64Png(url: string, max = 360): Promise<string> {
  const img = await loadImage(url);
  const scale = Math.min(1, max / Math.max(img.naturalWidth, img.naturalHeight));
  const canvas = document.createElement("canvas");
  canvas.width = Math.round(img.naturalWidth * scale);
  canvas.height = Math.round(img.naturalHeight * scale);
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("Canvas unavailable");
  ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
  return canvas.toDataURL("image/png").replace(/^data:image\/png;base64,/, "");
}

export async function generateEmbeddedArtKotlin(): Promise<string> {
  const entries: string[] = [];
  for (const key of Object.keys(PRODUCT_IMAGES) as ProductImageKey[]) {
    const b64 = await imageToBase64Png(PRODUCT_IMAGES[key]);
    const chunks = b64.match(/.{1,30000}/g) ?? [];
    entries.push(`        "${PRODUCT_RES_NAMES[key]}" to arrayOf(\n${chunks.map((c) => `            "${c}"`).join(",\n")},\n        )`);
  }
  return `package dev.ibridge.android

/**
 * Base64 copies of the 3D product renders, decoded with BitmapFactory.decodeByteArray so the
 * art renders even when only the Kotlin sources are copied into a project.
 * Generated by the iNA source viewer — full-resolution PNGs also live in res/drawable-nodpi/.
 */
object EmbeddedProductArt {
    private val CHUNKS: Map<String, Array<String>> by lazy {
        mapOf(
${entries.join(",\n")},
        )
    }

    fun base64(resName: String): String? = CHUNKS[resName]?.joinToString(separator = "")
}
`;
}

async function fetchBytes(url: string): Promise<Uint8Array> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Could not download ${url}`);
  return new Uint8Array(await res.arrayBuffer());
}

export async function buildProjectZip(): Promise<Blob> {
  const files: Record<string, Uint8Array> = {};
  const embedded = await generateEmbeddedArtKotlin();
  for (const f of SOURCE_FILES) {
    const content = f.name === EMBEDDED_ART_FILE ? embedded : f.content;
    files[`iNA/${f.path}`] = strToU8(content);
  }
  for (const key of Object.keys(PRODUCT_IMAGES) as ProductImageKey[]) {
    files[`iNA/app/src/main/res/drawable-nodpi/${PRODUCT_RES_NAMES[key]}.png`] = await fetchBytes(PRODUCT_IMAGES[key]);
  }
  for (const [fullPath, url] of Object.entries(BINARY)) {
    files[`iNA/${fullPath.replace(/^\/src\/android\//, "")}`] = await fetchBytes(url);
  }
  const zipped = zipSync(files, { level: 6 });
  return new Blob([zipped as BlobPart], { type: "application/zip" });
}

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 2000);
}
